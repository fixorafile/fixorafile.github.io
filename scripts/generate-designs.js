// Scans images/<category>/ and rebuilds designs.js automatically.
// File naming rule:  images/<category-slug>/<sub-category-slug>-<number>.webp
// Example:           images/banners-posters/event-banners-1.webp
const fs = require("fs");
const path = require("path");

const ROOT = process.cwd();
const EXTS = [".webp", ".jpg", ".jpeg", ".png"];

// OPTIONAL: old file names that do not follow the rule.
// "<category-slug>/<file-prefix>": "<sub-category-slug>"
const ALIASES = {
  "business-cards/corporate": "corporate-business-cards",
};

const slug = (s) =>
  s.toLowerCase().replace(/&/g, " ").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

const CATEGORIES = new Function(
  fs.readFileSync(path.join(ROOT, "categories.js"), "utf8") + "\nreturn CATEGORIES;"
)();

const designs = [];
const unmatched = [];

for (const cat of CATEGORIES) {
  const catSlug = slug(cat.name);
  const dir = path.join(ROOT, "images", catSlug);
  const dirOk = fs.existsSync(dir) && fs.statSync(dir).isDirectory();

  const subBySlug = new Map(cat.subs.map((s, i) => [slug(s), { name: s, order: i }]));
  const found = [];

  for (const file of dirOk ? fs.readdirSync(dir) : []) {
    const ext = path.extname(file).toLowerCase();
    if (!EXTS.includes(ext)) continue;
    const base = slug(path.basename(file, path.extname(file)));
    const m = base.match(/^(.*)-(\d+)$/);
    if (!m) { unmatched.push(`${catSlug}/${file}  (needs -<number> at the end)`); continue; }
    const subSlug = ALIASES[`${catSlug}/${m[1]}`] || m[1];
    const sub = subBySlug.get(subSlug);
    if (!sub) { unmatched.push(`${catSlug}/${file}  (no sub-category named "${m[1]}")`); continue; }
    found.push({ sub, num: parseInt(m[2], 10), file });
  }

  found.sort((a, b) => a.sub.order - b.sub.order || a.num - b.num);
  for (const f of found) {
    designs.push({
      category: cat.name,
      sub: f.sub.name,
      title: `${f.sub.name} Design ${f.num}`,
      image: encodeURI(`images/${catSlug}/${f.file}`),
    });
  }

  // Sub-category with a cover image but no design yet: show it using the cover.
  const covDir = path.join(ROOT, "images", "covers", "sub");
  for (const [sSlug, sub] of subBySlug) {
    if (found.some((f) => f.sub.name === sub.name)) continue;
    const cov = EXTS.map((e) => sSlug + e).find((n) => fs.existsSync(path.join(covDir, n)));
    if (cov) {
      designs.push({
        category: cat.name,
        sub: sub.name,
        title: `${sub.name} Design 1`,
        image: encodeURI(`images/covers/sub/${cov}`),
      });
    }
  }
}

let out = `// ============================================================
//  AUTO-GENERATED by scripts/generate-designs.js
//  Is file ko haath se edit mat karo, agli baar upload par overwrite ho jayegi.
//  Bas image upload karo:  images/<category>/<sub-category>-<number>.webp
// ============================================================
const DESIGNS = [
`;
let lastCat = "";
for (const d of designs) {
  if (d.category !== lastCat) { out += `  // --- ${d.category.toUpperCase()} ---\n`; lastCat = d.category; }
  out += `  { category: ${JSON.stringify(d.category)}, sub: ${JSON.stringify(d.sub)}, title: ${JSON.stringify(d.title)}, image: ${JSON.stringify(d.image)} },\n`;
}
out += "];\n";
fs.writeFileSync(path.join(ROOT, "designs.js"), out);

console.log(`designs.js updated: ${designs.length} designs`);
if (unmatched.length) {
  console.log("\nSkipped (name did not match the rule):");
  unmatched.forEach((u) => console.log("  - " + u));
}
